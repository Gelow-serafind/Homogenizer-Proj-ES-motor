/*******************************************************************************
* @filename:  ec11.h
* @brief:     EC11 旋转编码器驱动：A/B 相正交解码（4 倍频），无业务语义
* @note       高有效（公共端 5V + 外部 10k 下拉）；每格 = 4 个状态边沿
*******************************************************************************/
#ifndef EC11_H
#define EC11_H

#include <stdint.h>

void    ec11_init(void);        /* A/B 相 GPIO 配置（PC5/PC3） + 解码状态复位 */
void    ec11_ops(void);         /* 2ms 调用：采样 A/B → 状态表解码 */
int32_t ec11_take_delta(void);  /* 取累计增量（格，±120 饱和），取后清零 */

#endif /* EC11_H */
